# Adobe Photoshop "Save for Web" / Adobe 常用表在此不内置，另用 mozjpeg/cv2/PIL 实测生成。


def ijg_scale(q):
    q = max(1, min(100, q))
    if q < 50:
        return 5000 // q
    return 200 - q*2


def ijg_table(base, q, force_baseline=True):
    sf = ijg_scale(q)
    out = []
    for v in base:
        t = (v * sf + 50) // 100
        if t < 1:
            t = 1
        if t > 255 and force_baseline:
            t = 255
        if t > 32767:
            t = 32767
        out.append(t)
    return out
